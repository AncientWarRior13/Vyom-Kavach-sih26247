"""Head-to-head comparison at -25 dB: frozen 11-feature model (out-of-
distribution -- it was only ever trained on [-20,-10] dB) vs. the new
31-feature model (trained WITH -25 dB data).

This is intentionally NOT a fair fight in one specific sense, and that's
disclosed rather than hidden: the 11-feature model has never seen -25dB
noise during training, while the 31-feature model was trained on the
extended [-25,-10] range specifically so it would have. The honest question
this answers is "does the incumbent degrade gracefully under noise levels
it was never designed for, and does a purpose-built model trained for that
regime actually do better" -- not "which schema is intrinsically better."

The 11-feature test data here is generated by REUSING radarsense/simulator.py's
exact per-class physics (_class_block) -- imported, not duplicated or
modified -- with the SNR mapping extended to -25dB locally in this script
only. The frozen simulator.py, config.py, and final_model.joblib are never
touched or retrained.
"""

import json

import joblib
import numpy as np

from radarsense import config as C
from radarsense.metrics import full_metrics
from radarsense.optimize import threshold_predict
from radarsense.simulator import _class_block

EXTENDED_SNR_RANGE = (-25.0, -10.0)


def generate_extended_snr_test(n_samples=8000, seed=C.SEED + 999):
    """Same per-class physics as the frozen simulator (_class_block, imported
    unmodified), SNR mapped into the EXTENDED [-25,-10] band for this
    stress-test generation only -- config.py's frozen SNR_RANGE_DB is never
    changed."""
    rng = np.random.default_rng(seed)
    import pandas as pd
    frames = []
    for cls, frac in C.CLASS_PROPORTIONS.items():
        n = int(round(n_samples * frac))
        block = _class_block(rng, cls, n)

        raw = block["rcs_estimate"] - 40 * np.log10(block["range_m"])
        lo, hi = np.percentile(raw, [2, 98])
        snr = EXTENDED_SNR_RANGE[0] + (raw - lo) / (hi - lo) * (EXTENDED_SNR_RANGE[1] - EXTENDED_SNR_RANGE[0])
        snr = np.clip(snr + rng.normal(0, 1.0, n), *EXTENDED_SNR_RANGE)
        block["snr_db"] = snr

        noise_frac = (C.SNR_RANGE_DB[1] - snr) / (C.SNR_RANGE_DB[1] - C.SNR_RANGE_DB[0])
        noise_scales = {
            "doppler_velocity": 4.0, "rcs_estimate": 3.0,
            "micro_doppler_bandwidth": 60.0, "micro_doppler_jitter": 0.12,
            "range_m": 30.0, "azimuth_deg": 2.0, "altitude_m": 50.0,
            "velocity_variance": 2.0, "acceleration": 1.5,
        }
        for feat, scale in noise_scales.items():
            block[feat] = block[feat] + noise_frac * scale * rng.standard_normal(n)

        block["doppler_velocity"] = np.clip(block["doppler_velocity"], -50, 50)
        block["rcs_estimate"] = np.clip(block["rcs_estimate"], -20, 20)
        block["micro_doppler_bandwidth"] = np.clip(block["micro_doppler_bandwidth"], 0, 500)
        block["micro_doppler_jitter"] = np.clip(block["micro_doppler_jitter"], 0, 1)
        block["range_m"] = np.clip(block["range_m"], 50, 5000)
        block["azimuth_deg"] = np.clip(block["azimuth_deg"], -180, 180)
        block["altitude_m"] = np.clip(block["altitude_m"], 0, 3000)
        block["velocity_variance"] = np.clip(block["velocity_variance"], 0, None)
        block["acceleration"] = np.clip(block["acceleration"], -10, 10)
        block["doppler_freq_shift"] = 2 * block["doppler_velocity"] * C.CARRIER_FREQ_HZ / C.C_LIGHT

        df = pd.DataFrame(block)
        df[C.LABEL_COLUMN] = cls
        frames.append(df)

    data = pd.concat(frames, ignore_index=True)
    data = data[C.FEATURE_COLUMNS + [C.LABEL_COLUMN]]
    return data.sample(frac=1.0, random_state=seed).reset_index(drop=True)


def main():
    print("generating extended-SNR test data via the FROZEN simulator's exact "
          "per-class physics (simulator.py untouched, unmodified)...")
    ext_test = generate_extended_snr_test()

    model11 = joblib.load(C.MODELS_DIR / "final_model.joblib")
    meta = json.loads((C.MODELS_DIR / "final_model_meta.json").read_text())

    deep11 = ext_test[ext_test.snr_db <= -23]
    proba11 = model11.predict_proba(deep11[C.FEATURE_COLUMNS])
    pred11 = threshold_predict(proba11, meta["drone_threshold_deployed"])
    m11 = full_metrics(deep11[C.LABEL_COLUMN], pred11, proba11)
    m11["n"] = len(deep11)
    print(f"\n11-feature FROZEN model, out-of-distribution SNR<=-23dB (n={len(deep11)}):")
    print(f"  accuracy={m11['accuracy']:.4f} macro_f1={m11['macro_f1']:.4f} "
          f"drone_recall={m11['recall_drone']:.4f}")

    feat31 = json.loads((C.REPORTS_DIR / "feat31_results.json").read_text())
    m31 = feat31["deep_low_snr_leq_minus23db"]
    print(f"\n31-feature model, TRAINED-for-this-regime SNR<=-23dB (n={m31['n']}):")
    print(f"  accuracy={m31['accuracy']:.4f} macro_f1={m31['macro_f1']:.4f} "
          f"drone_recall={m31['recall_drone']:.4f}")

    winner = "31-feature" if m31["accuracy"] > m11["accuracy"] else "11-feature"
    out = {
        "comparison_note": (
            "NOT a fair fight in one specific sense, disclosed not hidden: the "
            "11-feature model was never trained on SNR below -20dB (out of "
            "distribution here); the 31-feature model WAS trained on "
            "[-25,-10]dB. This tests graceful-degradation-under-novel-noise "
            "for the incumbent vs. purpose-built-for-this-regime for the "
            "challenger, not an intrinsic schema comparison."),
        "snr_slice_tested": "<= -23 dB",
        "model_11feature_frozen_ood": m11,
        "model_31feature_trained_for_regime": m31,
        "higher_accuracy_at_this_slice": winner,
    }
    (C.REPORTS_DIR / "feat31_vs_11feature_comparison.json").write_text(json.dumps(out, indent=2))
    print(f"\nhigher accuracy at SNR<=-23dB: {winner}")
    print(f"results -> {C.REPORTS_DIR / 'feat31_vs_11feature_comparison.json'}")


if __name__ == "__main__":
    main()
